// Generates src/theme/colors.css: the colour tokens behind JTracker's light
// and dark themes. Run with `npm run theme:colors` after changing the scales.
//
// Light mode keeps Tailwind's own palette exactly. Dark mode uses the navy
// scale from the JTracker icon system for slate and white, and mirrors every
// other palette (50 ↔ 950, 100 ↔ 900, …) so tinted backgrounds become deep
// tints and dark text becomes light text.

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const colors = require('tailwindcss/colors');

export const PALETTES = ['slate', 'gray', 'zinc', 'red', 'orange', 'amber', 'yellow', 'green', 'emerald', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'rose'];
export const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];

// Navy scale from the icon system (page #141C31, card #1E2740, active #273357,
// text #F9FAFF / #C3CBDD / #A8B2CA).
const DARK_SLATE = {
  white: '#1E2740',
  50: '#141C31',
  100: '#273357',
  200: '#313D63',
  300: '#44507A',
  400: '#8A95B3',
  500: '#A8B2CA',
  600: '#C3CBDD',
  700: '#D8DEEB',
  800: '#E9EDF5',
  900: '#F9FAFF',
  950: '#FFFFFF',
};

const rgb = (hex) => {
  const value = hex.replace('#', '');
  const n = parseInt(value.length === 3 ? value.replace(/./g, '$&$&') : value, 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};

const mirror = (shade) => SHADES[SHADES.length - 1 - SHADES.indexOf(shade)];

// Tinted backgrounds (50–200) are blended into the navy card colour so status
// cards read as calm tints of the surface rather than saturated blocks.
const TINT_BLEND = { 50: 0.55, 100: 0.4, 200: 0.25 };
const mix = (hex, baseHex, weight) => {
  const [r1, g1, b1] = rgb(hex).split(' ').map(Number);
  const [r2, g2, b2] = rgb(baseHex).split(' ').map(Number);
  const channel = (a, b) => Math.round(a * (1 - weight) + b * weight).toString(16).padStart(2, '0');
  return `#${channel(r1, r2)}${channel(g1, g2)}${channel(b1, b2)}`;
};

const light = [`  --jt-white: ${rgb('#ffffff')};`];
const dark = [`  --jt-white: ${rgb(DARK_SLATE.white)};`];
for (const palette of PALETTES) {
  for (const shade of SHADES) {
    light.push(`  --jt-${palette}-${shade}: ${rgb(colors[palette][shade])};`);
    const mirrored = colors[palette][mirror(shade)];
    const darkHex =
      palette === 'slate' ? DARK_SLATE[shade] : TINT_BLEND[shade] ? mix(mirrored, DARK_SLATE.white, TINT_BLEND[shade]) : mirrored;
    dark.push(`  --jt-${palette}-${shade}: ${rgb(darkHex)};`);
  }
}

// .keep-dark panels are navy in light mode (bg-slate-900 + text-white). In
// dark mode they keep their light-mode colours, with the navy raised a step
// (#273357, the icon system's active colour) so they still stand out.
const KEEP_DARK = { 950: '#202D64', 900: '#273357', 800: '#313D63', 700: '#44507A' };
const keepDark = light.map((line) => {
  const match = line.match(/--jt-slate-(\d+):/);
  return match && KEEP_DARK[match[1]] ? `  --jt-slate-${match[1]}: ${rgb(KEEP_DARK[match[1]])};` : line;
});

const css = `/* Generated by scripts/generate-theme-colors.mjs. Do not edit by hand. */

/* Light: Tailwind's palette. .theme-light keeps a region light inside the
   dark theme (documents such as CV and résumé previews). */
:root,
.theme-light {
${light.join('\n')}
}

:root.dark {
${dark.join('\n')}
}

:root.dark .theme-light {
${light.join('\n')}
}

:root.dark .keep-dark {
${keepDark.join('\n')}
}
`;

writeFileSync(new URL('../src/theme/colors.css', import.meta.url), css);
console.log('Wrote src/theme/colors.css');
